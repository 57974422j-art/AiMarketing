export type SegTag = 'brand' | 'scene' | 'craft' | 'item' | 'end'

export function segTag(title: string, idx: number, total: number): SegTag {
  const t = String(title || '')
  if (total > 1 && idx >= total - 1) return 'end'
  if (/(门头|招牌|店名|门脸|门口|外景|夜景|霓虹|牌匾|灯箱|街景|巷口|大楼|外观)/.test(t)) return 'brand'
  if (/(一桌|满桌|圆桌|围坐|坐满|人多|热闹|环境|装修|院子|大厅|包间|卡座|靠窗|落地窗|吧台|走廊|角落|陈列|摆满)/.test(t)) return 'scene'
  if (/(切|烫|下锅|出锅|现做|现烤|现炸|手工|爆炒|翻滚|沸腾|冒泡|起锅|上桌|端来|淋|撒|拌|捣|揉|洗|剪)/.test(t)) return 'craft'
  return 'item'
}

/* 每个标签对应的「这段该写什么 / 不许写什么」——一行一句，喂给写口播那一步。
   ★第二个参数 `nth`：**同一标签第几次出现**（从 0 开始）⇒ 同标签内部**轮换角度**。
   为什么必须有：实测一单 15 段里 11 段都是"单品特写"⇒ 若都写"这一口脆嫩弹香"，
   等于换汤不换药（和"抄画面字"一样同质化）。轮换角度才能让全片有变化。 */
export function tagRule(tag: SegTag, nth = 0): string {
  if (tag === 'brand') return '写**品牌 / 位置 / 氛围**（开了多少年、在哪条街、什么调性）；**禁止**喊折扣、禁止写口感'
  if (tag === 'scene') {
    const a = [
      '写**人气 / 热闹**（一桌人、坐得满、锅一开就热闹）；可带"值"的口吻，但**不许编价格**',
      '写**环境 / 干净整洁**（桌面清爽、灯光舒服、坐得住）',
      '写**适合什么场合**（下班来、带家人、朋友聚、一个人也行）',
    ]
    return a[nth % a.length]
  }
  if (tag === 'craft') {
    const a = [
      '写**工艺 / 讲究**（手切、老法子、现做、不用半成品）',
      '写**火候 / 时间**（几秒、几上几下、什么火）',
      '写**师傅 / 手艺**（刀工、手上功夫、一天备多少）',
    ]
    return a[nth % a.length]
  }
  if (tag === 'end') return '写**收尾 / 邀请**（下班来坐坐、下次还来），一句收住'
  // item：单品特写最多，必须轮换角度
  const a = [
    '写**这一口的卖点 / 口感**（脆/嫩/弹/香/汁水），一个点就够',
    '写**怎么吃最对**（几秒、蘸什么、先吃哪个）',
    '写**和别处不一样的地方**（更厚 / 更脆 / 更实在 / 别家没有）',
    '写**什么人来会喜欢**（爱辣的、带孩子的、一个人来的）',
    '写**吃完什么感觉**（满足 / 停不下来 / 还想再来一份）',
  ]
  return a[nth % a.length]
}

/** 估算时长（秒）= 4.5 字/秒 —— 与成片线老口径一致。
 *  ⚠️ **只用于卡片上给个参考**；真正时长一律以 TTS 实测为准（本项目写死的纪律，别拿估算值去排时间轴）。 */
export function estimateSec(text: string): number {
  const n = [...String(text || '').replace(/\s/g, '')].length
  return n ? Math.max(1.2, Math.round((n / 4.5) * 10) / 10) : 0
}
