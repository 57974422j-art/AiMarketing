    if (i === slot) {
      s.fx = DAILY_FX_CUT[off % DAILY_FX_CUT.length] + '#' + ((off >> 1) % 2)
      return
    }
    // 安静组轮换：id 相邻必不同（切分型 id 与安静组天然不同，所以不用额外避让）
