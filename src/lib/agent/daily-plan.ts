    /* ★VF_MOTION_RULES_V1：横屏同样适用（实测那次就是竖屏撞的，横屏写法一样会撞）。 */
    '   · **禁止** 用 `animation` / `@keyframes` 承载 `--p`（引擎只改 `--p` 的值，不会重算动画 ⇒ 画面不动）；',
