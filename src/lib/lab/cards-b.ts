/**
 * ★LAB_CARDS_B（2026-10-30 用户定案「先A后B」）
 * =============================================================================
 * B 组：**12 张段落类型卡** —— 比 A 粗一层，每张说"这一段是什么性质"，并指定
 * **固定搭配 2~3 张 A 手法**。
 *
 * A 和 B 的关系：
 *   A（25 张）= 手法（怎么排）
 *   B（12 张）= 段落类型（这一段干什么）+ 推荐用哪几张 A
 *        ↓
 *   ⇒ B 模式 = 系统先给每段分配一个"类型"，模型再按类型里的 A 卡实现
 *   ⇒ A 模式 = 模型自己看素材挑手法（更自由，也更不稳定）
 *
 * 为什么需要 B：纯 A 模式下模型容易"每段都挑最简单的那张"（大字 + 图），
 * 导致整片节奏雷同。B 先把节奏定下来（钩子/细节/情绪/落版），再用 A 落地。
 */

export type SegmentCard = {
  id: string
  name: string
  /** 这一段在全片里承担什么 */
  role: string
  /** 推荐搭配的 A 手法（按优先级） */
  useA: string[]
  /** 这一段的硬要求（很少，只保留必须的） */
  must?: string
}

