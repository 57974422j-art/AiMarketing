/** 给提示词用：渲染成紧凑列表 */
export function renderCardsB(): string {
  return CARDS_B.map((c) =>
    `${c.id} **${c.name}** —— ${c.role}\n  推荐手法：${c.useA.join(' / ')}`
    + (c.must ? `\n  硬要求：${c.must}` : '')
  ).join('\n\n')
}

