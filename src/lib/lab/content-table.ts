/** 公共规则（所有内容类型都适用） */
export const COMMON_RULES = [
  '**每段至少 3 类装饰**（背景纹理 / 徽章 / 小装饰 / 三层描边 / 贴纸 / 圆角）—— 少于 3 类，画面就是"半成品"',
  '**相邻三段不许同视觉类型**（8 种：纯排版 / 满幅大图 / 图文分栏 / 多图错落 / 图切片 / 图形主图 / 数据图表 / 特写裁切）',
  '**图片不许压暗**：`brightness` 不低于 0.9、`contrast` 不高于 1.15（压暗 + 拉对比 = 看起来糊、旧、廉价）',
]

/** 按 id 取 */
export function getContentType(id?: string): ContentType | undefined {
  if (!id) return undefined
  return CONTENT_TYPES.find((c) => c.id === id)
}

/** 渲染成 prompt 段 */
export function renderContentType(id?: string): string {
  const ct = getContentType(id)
  if (!ct) return ''

  const lines: string[] = []
  lines.push(`【内容类型 · ${ct.name}】`)
  lines.push(`适用：${ct.when}`)
  lines.push('')
  lines.push('**这一类必须有的技法**（缺一条就会散）：')
  ct.skills.forEach((s, i) => lines.push(`  ${i + 1}. ${s}`))
  lines.push('')
  lines.push(`**配色策略**：${ct.palette}`)
  lines.push('')
  lines.push(`**节奏**：${ct.rhythm}`)
  lines.push('')
  lines.push('**❌ 这一类明确不要**（加了会毁掉气质）：')
  ct.avoid.forEach((s) => lines.push(`  · ${s}`))
  lines.push('')
  lines.push('**公共规则（所有类型都适用）**：')
  COMMON_RULES.forEach((s) => lines.push(`  · ${s}`))
  return lines.join('\n')
}
