/**
 * ★LAB_REVIEW（2026-10-31 用户定案「要做都做掉，全部做完」）
 * =============================================================================
 * **第二轮：自评返修** —— 学 `mg-styles-15` 的 rubric.md 两段式流程：
 *
 *   第一步：独立评审（打分 + 5~10 条带具体数字的修改意见）
 *   第二步：按意见改（保留优点，只改问题）
 *        ↓
 *   他们 15 支片**每支都走了两轮**，并明说「单次运行通常达不到成片水准」。
 *
 * 我们的实现：**同一份 HTML 发回去，让它先自评再重写**（一次调用完成两件事，
 * 比"先出报告再改"省一半 token）。
 *
 * ⚠️ 代价：一次出片变两次调用 ⇒ 费用翻倍（用户已知：B 档 3 分 → 6 分）。
 */

export type ReviewOpts = {
  /** 第一次生成的完整 HTML */
  html: string
  /** 画布尺寸，用于它在改进时不越界 */
  W: number
  H: number
  /** 目标时长（用于检查节奏） */
  maxSeconds?: number
}

/** 第一步+第二步合并：自评 + 按自评重写 */
export function buildReviewPrompt(o: ReviewOpts): string {
  const { html, W, H } = o

  return `你是**独立评审**（不是作者）。下面这条片子是另一个 AI 做的，你要：
① 按 7 个维度**严格打分**；② 挑出最影响观感的 5~8 处问题；③ **直接重写整份 HTML** 把问题修掉。

⚠️ 打分纪律：**首次做出来的东西通常只值 5~7 分，不要灌水到 8 以上**。
   5 = 学生作业 / 6 = 模板级 / 7 = 专业 / 8 = 高端工作室 / 9 = 获奖入围

【评分维度（1~10）】
  1. **风格保真** —— 它有没有一个贯穿全片、能说清楚的视觉方向？
     配色是不是"顺色"（素材暖画面也暖）？**顺色直接扣到 5 分以下**。
  2. **概念冲击** —— 第一屏有没有钩子？全片有没有 hero moment？
     如果没有一个"最强的 1~2 秒"，最高给 6。
  3. **动效工艺** —— 缓动是不是具体曲线（不是默认 ease）？有没有预备—动作—跟随？
     有没有**死帧**（整段画面不动）？有死帧最高 6。
  4. **排版** —— 最大字 / 最小字 ≥ 8 倍吗？有没有不对称？有没有一处出血或被裁的元素？
  5. **质感** —— 有没有颗粒/暗角/细线/描边这类"多做的一层"？
  6. **节奏** —— 每段时长是否**不一样**？有没有快切段和长镜段？全是 3~4 秒一律最高 6。
  7. **技术** —— 无外部资源 / 无 emoji 图标 / 字体只用占位族名 / 首帧不空白。

【一票否决（出现任意一条，必须修）】
  · **generic or AI-template** —— 看起来像"任何题材都能套的模板"
  · 中文文案不自然（像说明书 / 像机翻）
  · 字体回退或豆腐块
  · 图片超出画布被裁掉半截

【修改要求】
  · 至少 **3 条**必须是"提升 wow factor"，不能全是打磨细节
  · 每条给出**具体数值**（缓动曲线 / 毫秒 / px / 色值），不要写"优化一下动效"
  · **不要砍掉它做对的地方**（如果某个手法很好，保留并加强）
  · 改完的页面必须仍然守这些技术底线：
    - 画布 ${W}×${H}，section.sec data-start / data-duration 结构
    - window.__seek(t) 接口**原样保留**
    - 每段有不透明背景，整段 opacity 由 --p 控制
    - 无外部资源、字体只用 TXT-Serif / TXT-Sans
    - 图片 top + 高度 ≤ ${o.H - 20}

【输出】
**只输出改进后的完整 HTML**（<!DOCTYPE html> 到 </html>），不要输出评分表、不要解释、不要 markdown 围栏。

---

【待评审的 HTML】
${html}`.trim()
}
