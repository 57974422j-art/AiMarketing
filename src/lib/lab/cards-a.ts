/** 给提示词用：把卡渲染成紧凑列表 */
export function renderCardsA(): string {
  return CARDS_A.map((c) =>
    `${c.id} **${c.name}**\n  用在哪：${c.when}\n  怎么做：${c.how}`
    + (c.pitfall ? `\n  ⚠️ 坑：${c.pitfall}` : '')
  ).join('\n\n')
}
